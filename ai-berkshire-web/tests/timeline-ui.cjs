/* Run only through ops.check's isolated service and synthetic report fixtures. */
const assert = require("node:assert/strict");
const path = require("node:path");
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const output = process.env.UI_TEST_OUTPUT || "playwright-results";

(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const screenshot = name => page.screenshot({path:path.join(output, name + ".png"), fullPage:true});
  const companies = page.locator("#tl-company");
  const status = page.locator("#tl-status");
  const waitCompany = async name => {
    const response = page.waitForResponse(r => {
      const url = new URL(r.url());
      return url.pathname === '/api/timeline/companies' && url.searchParams.get('q') === name && r.status() === 200;
    });
    if (await page.locator('#tl-company-search').inputValue() === name) await page.locator('#btn-tl-refresh').click();
    else await page.locator('#tl-company-search').fill(name);
    await response;
    await page.waitForFunction(() => !document.querySelector('#tl-company').disabled);
    await page.locator(`#tl-company option[value="${name}"]`).waitFor({state:"attached"});
  };
  try {
    await page.goto("http://127.0.0.1:8765");
    await page.locator("#login-username").fill("admin");
    await page.locator("#login-password").fill(process.env.VC_SMOKE_PASSWORD || "visual-test-password");
    await page.locator("#btn-login").click();
    await page.locator("#login-overlay").waitFor({state:"hidden"});
    await page.locator('.nav-item[data-page="timeline"]').click();
    await page.waitForFunction(() => !document.querySelector('#tl-company-next').disabled);
    assert.equal(await page.locator('#tl-company option').count(), 31);
    await page.locator('#tl-company-next').click();
    await page.locator('#tl-company-page-info').filter({hasText:'第2页'}).waitFor();
    await waitCompany("时间线验收公司");
    assert.equal(await companies.inputValue(), "");
    assert.ok(await page.locator("#btn-tl-load").isDisabled());
    await companies.selectOption("时间线验收公司");
    await status.filter({hasText:"「时间线验收公司」共 2 份报告"}).waitFor();
    await page.locator('#timeline-dates-period').selectOption('custom');
    await page.locator('#timeline-dates-from').fill('2026-10-15');
    await page.locator('#timeline-dates-to').fill('2026-10-15');
    await page.locator('#tl-company option').filter({hasText:'时间线验收公司（1 份'}).waitFor({state:'attached'});
    await companies.selectOption('时间线验收公司');
    await status.filter({hasText:'「时间线验收公司」共 1 份报告'}).waitFor();
    assert.equal(await page.locator('#tl-list .tl-item').count(),1);
    await page.locator('#timeline-dates-period').selectOption('all');
    await status.filter({hasText:'「时间线验收公司」共 2 份报告'}).waitFor();
    assert.equal(await page.locator("#tl-list .tl-item").count(), 2);
    assert.match(await page.locator("#tl-stats").textContent(), /8\/10 → 6\/10/);
    assert.equal(await page.locator("#tl-chart polyline").count(), 1);
    await screenshot("timeline-desktop");
    await page.locator("#tl-list .tl-title").first().press("Enter");
    await page.locator("#report-modal.open").waitFor();
    assert.match(await page.locator("#modal-content").textContent(), /时间线合成研究/);
    await page.locator("#modal-close").click();
    await waitCompany("分页验收专题");
    await companies.selectOption("分页验收专题");
    await status.filter({hasText:"共 45 份报告，当前显示 1–20"}).waitFor();
    assert.equal(await page.locator('#tl-list .tl-item').count(), 20);
    const firstPage = await page.locator('#tl-list .tl-title').allTextContents();
    await page.locator('#tl-next').click();
    await status.filter({hasText:'当前显示 21–40'}).waitFor();
    const secondPage = await page.locator('#tl-list .tl-title').allTextContents();
    assert.equal(secondPage.length, 20);
    assert.ok(!secondPage.some(title => firstPage.includes(title)));
    await page.locator('#tl-prev').click();
    await status.filter({hasText:'当前显示 1–20'}).waitFor();
    assert.deepEqual(await page.locator('#tl-list .tl-title').allTextContents(), firstPage);
    await waitCompany("界面测试示例公司");
    await companies.selectOption("界面测试示例公司");
    await status.filter({hasText:"「界面测试示例公司」共"}).waitFor();
    assert.match(await page.locator("#tl-list").textContent(), /站内生成/);
    await waitCompany("橡树公司");
    await companies.selectOption("橡树公司");
    await status.filter({hasText:"「橡树公司」共"}).waitFor();
    assert.match(await page.locator("#tl-list").textContent(), /本地导入/);
    await page.locator("#tl-list .tl-title").first().click();
    await page.locator("#report-modal.open").waitFor();
    assert.match(await page.locator("#modal-meta").textContent(), /本地导入/);
    await page.locator("#modal-close").click();
    await waitCompany("时间线验收公司");
    await companies.selectOption("时间线验收公司");
    await status.filter({hasText:"「时间线验收公司」共 2 份报告"}).waitFor();
    await page.setViewportSize({width:430,height:932});
    await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await screenshot("timeline-mobile");

    const route = "**/api/timeline/companies*";
    await page.route(route, request => request.fulfill({status:500, contentType:"application/json", body:JSON.stringify({detail:"合成网络错误"})}));
    await page.locator("#btn-tl-refresh").click();
    await status.filter({hasText:"公司列表加载失败"}).waitFor();
    assert.equal(await companies.inputValue(), "");
    assert.ok(await page.locator("#btn-tl-load").isDisabled());
    await screenshot("timeline-error-mobile");
    await page.unroute(route);
    await waitCompany("时间线验收公司");

    await page.route(route, request => request.fulfill({status:200, contentType:"application/json", body:'{"items":[]}'}));
    await page.locator('#tl-company-search').fill('');
    await status.filter({hasText:"所选条件下暂无公司或专题"}).waitFor();
    assert.match(await companies.textContent(), /暂无可用报告/);
    assert.ok(await page.locator("#btn-tl-load").isDisabled());
    assert.ok(await page.locator("#tl-stats-card").isHidden());
    await screenshot("timeline-empty-mobile");
    await page.unroute(route);
    await waitCompany("时间线验收公司");
    await page.route(route, () => {});
    await page.locator('#btn-tl-refresh').click();
    await status.filter({hasText:'请求超时'}).waitFor({timeout:12000});
    assert.ok(await page.locator('#btn-tl-refresh').isEnabled());
    await page.unroute(route);
    await waitCompany("时间线验收公司");
    const memory = await page.evaluate(async () => {
      const response = await fetch("/api/memory/status", {headers:{Authorization:"Bearer " + localStorage.getItem("vc_token")}});
      return response.json();
    });
    assert.equal(memory.docs, 0);
    assert.equal(memory.conclusions, 0);
    assert.deepEqual(errors, []);
    console.log("Timeline UI passed: searchable paged companies, 20-report pages, all sources/readers, desktop/mobile, timeout/error/empty recovery.");
  } catch (error) {
    await screenshot("timeline-failure").catch(() => {});
    throw error;
  } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
